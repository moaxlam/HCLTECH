def work_plan(count: int, batch_size: int, first_id: int = 1001) -> list[tuple[str, int, int]]:
    """Round-robin batches so both programmes and both batches are represented."""
    options = [("B.Tech CSE", 2023), ("B.Tech CSE", 2024), ("B.Tech ECE", 2023), ("B.Tech ECE", 2024)]
    plan: list[tuple[str, int, int]] = []
    remaining = count
    index = 0
    while remaining > 0:
        programme, batch_year = options[index % len(options)]
        size = min(batch_size, remaining)
        plan.append((programme, batch_year, size))
        remaining -= size
        index += 1
    return plan


def generate_from_llm(
    args, count: int, first_id: int = 1001, budget_seconds: float = 0.0
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Ask the model for ``count`` students. Stops early when the budget runs out."""
    rng = random.Random(args.seed)
    plan = work_plan(count, args.batch_size, first_id)
    students: list[dict[str, Any]] = []
    repairs: list[str] = []
    raw_dir = Path(args.out) / "generated_raw"
    raw_dir.mkdir(parents=True, exist_ok=True)
    next_id = first_id
    calls = 0
    rejected_batches = 0
    budget_exhausted = False
    started = time.monotonic()

    for programme, batch_year, size in plan:
        if budget_seconds and time.monotonic() - started > budget_seconds:
            budget_exhausted = True
            print(f"  ! model time budget of {budget_seconds:.0f}s reached; filling the rest deterministically")
            break
        first_id = next_id
        last_id = next_id + size - 1
        prompt = build_batch_prompt(size, programme, batch_year, first_id, last_id)
        accepted: list[dict[str, Any]] = []
        for attempt in range(1, args.retries + 2):
            try:
                raw = call_ollama(prompt, args.model, args.host, args.temperature, args.seed + attempt)
            except (urllib.error.URLError, TimeoutError, OSError) as exc:
                print(f"  ! model unavailable ({exc}); falling back to the deterministic producer")
                return [], {"model_unavailable": str(exc), "model_calls": calls}
            calls += 1
            (raw_dir / f"batch_{first_id}_{attempt}.json").write_text(raw, encoding="utf-8")
            candidates = extract_students(raw)
            for candidate in candidates:
                fixed, batch_repairs = repair_student(candidate)
                repairs.extend(batch_repairs)
                if _candidate_is_usable(fixed, programme, batch_year, first_id, last_id):
                    accepted.append(fixed)
            if len(accepted) >= size:
                break
            print(f"  · attempt {attempt}: {len(accepted)}/{size} usable rows, retrying")
        if len(accepted) < size:
            rejected_batches += 1
            print(f"  · batch {first_id}-{last_id} short of the contract; filling deterministically")
            accepted.extend(
                deterministic_batch(size - len(accepted), programme, batch_year, first_id + len(accepted), rng)
            )
        accepted = accepted[:size]
        for index, record in enumerate(accepted):
            record["student_id"] = f"S{first_id + index:04d}"
        students.extend(accepted)
        next_id = first_id + size

    log = {
        "model": args.model,
        "model_calls": calls,
        "rejected_or_topped_up_batches": rejected_batches,
        "model_block_budget_exhausted": budget_exhausted,
        "repairs": repairs,
    }
    return students, log


def _candidate_is_usable(candidate: dict[str, Any], programme: str, batch_year: int, first: int, last: int) -> bool:
    student_id = str(candidate.get("student_id", ""))
    if not re.match(r"^S\d{4}$", student_id):
        return False
    if not first <= int(student_id[1:]) <= last:
        return False
    if str(candidate.get("programme", "")).strip() != programme:
        return False
    if int(candidate.get("batch_year") or 0) != batch_year:
        return False
    attendance = candidate.get("attendance") or []
    results = candidate.get("results") or []
    if not attendance or not results:
        return False
    allowed = set(PROGRAMME_COURSES[programme])
    if any(str(row.get("course_code")) not in allowed for row in attendance + results):
        return False
    if not 0.0 <= float(candidate.get("cgpa") or -1) <= 10.0:
        return False
    return True


