def deterministic_batch(
    count: int, programme: str, batch_year: int, first_id: int, rng: random.Random
) -> list[dict[str, Any]]:
    courses = PROGRAMME_COURSES[programme]
    semester = 5 if batch_year == 2023 else 3
    session = "2026-MAY" if batch_year == 2023 else "2026-DEC"
    students = []
    for offset in range(count):
        student_id = f"S{first_id + offset}"
        attendance = []
        for course in courses:
            held = rng.choice([36, 38, 40, 42, 44])
            ratio = rng.uniform(0.62, 0.98)
            attendance.append(
                {
                    "course_code": course,
                    "classes_held": held,
                    "classes_attended": min(held, int(round(held * ratio))),
                }
            )
        results = []
        for course in courses[: rng.choice([2, 3])]:
            internal = rng.randint(12, 30)
            external = rng.randint(0, 68)
            total = internal + external
            results.append(
                {
                    "course_code": course,
                    "exam_session": session,
                    "exam_type": "REGULAR",
                    "internal_marks": internal,
                    "external_marks": external,
                    "total_marks": total,
                    "max_marks": MAX_TOTAL,
                    "result": expected_result(total, external, MAX_TOTAL),
                }
            )
        student = {
            "student_id": student_id,
            "full_name": f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}",
            "programme": programme,
            "batch_year": batch_year,
            "current_semester": semester,
            "cgpa": round(rng.uniform(4.6, 9.6), 2),
            "active_backlogs": 0,
            "attendance": attendance,
            "results": results,
        }
        student, _ = repair_student(student)
        students.append(student)
    return students


