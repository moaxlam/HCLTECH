MONTH_WORDS = {
    "jan": "MAY", "feb": "MAY", "mar": "MAY", "apr": "MAY", "may": "MAY", "jun": "MAY",
    "jul": "DEC", "aug": "DEC", "sep": "DEC", "oct": "DEC", "nov": "DEC", "dec": "DEC",
}


def normalise_session(raw: Any) -> str:
    """Coerce whatever the model wrote into ``YYYY-MAY`` or ``YYYY-DEC``.

    The exam sessions in this corpus are 2026-MAY (even semester) and 2026-DEC
    (odd semester) per EXAM-RULES-2025 clause 2.1, so anything in the first half of
    a year maps to MAY and anything in the second half maps to DEC.
    """
    text = str(raw or "").strip()
    year_match = re.search(r"(20\d{2})", text)
    year = year_match.group(1) if year_match else ""
    lowered = text.casefold()
    for word, session in MONTH_WORDS.items():
        if word in lowered:
            return f"{year}-{session}" if year else ""
    month_match = re.search(r"-(\d{1,2})[-\s]|\s(\d{1,2})[-/]\d{2}", text)
    if month_match and year:
        month = int(month_match.group(1) or month_match.group(2))
        return f"{year}-{'MAY' if month <= 6 else 'DEC'}"
    return text.upper() if re.match(r"^20\d{2}-(MAY|DEC)$", text.upper()) else ""


def repair_student(student: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Recompute derived fields the model is not trusted to compute.

    ``total_marks`` is always internal + external and ``result`` always follows
    EXAM-RULES-2025 clauses 3.2 and 3.3. Every change is logged.
    """
    repairs: list[str] = []
    student_id = str(student.get("student_id", "?")).strip()
    fixed_results = []
    for row in student.get("results", []) or []:
        if not isinstance(row, dict):
            continue
        session = normalise_session(row.get("exam_session"))
        if not session:
            repairs.append(
                f"{student_id}/{row.get('course_code')}: dropped a result row with an unreadable exam_session "
                f"({row.get('exam_session')!r})"
            )
            continue
        if session != str(row.get("exam_session", "")).strip():
            repairs.append(
                f"{student_id}/{row.get('course_code')}: exam_session {row.get('exam_session')!r} -> {session}"
            )
        try:
            internal = int(str(row.get("internal_marks", 0)).strip())
            external = int(str(row.get("external_marks", 0)).strip())
        except ValueError:
            repairs.append(f"{student_id}: dropped a result row with non-numeric marks")
            continue
        result = str(row.get("result", "")).strip().upper()
        if result == "ABSENT" and external != 0:
            repairs.append(
                f"{student_id}/{row.get('course_code')}: ABSENT row had {external} paper marks; set to 0"
            )
            external = 0
        total = internal + external
        if result in {"ABSENT", "DETAINED"}:
            pass
        elif result == "PASS" and expected_result(total, external, MAX_TOTAL) != "PASS":
            repairs.append(
                f"{student_id}/{row.get('course_code')}: result PASS corrected to FAIL "
                f"(total={total}, external={external})"
            )
            result = "FAIL"
        elif result not in {"PASS", "FAIL"}:
            repairs.append(f"{student_id}/{row.get('course_code')}: unknown result {result!r} recomputed")
            result = expected_result(total, external, MAX_TOTAL)
        elif result == "FAIL" and expected_result(total, external, MAX_TOTAL) == "PASS":
            repairs.append(
                f"{student_id}/{row.get('course_code')}: result FAIL corrected to PASS "
                f"(total={total}, external={external})"
            )
            result = "PASS"
        if int(str(row.get("total_marks", -1)).strip() or -1) != total:
            repairs.append(f"{student_id}/{row.get('course_code')}: total_marks recomputed to {total}")
        if int(str(row.get("max_marks", 0)).strip() or 0) != MAX_TOTAL:
            repairs.append(f"{student_id}/{row.get('course_code')}: max_marks set to {MAX_TOTAL}")
        exam_type = str(row.get("exam_type", "REGULAR")).strip().upper() or "REGULAR"
        if exam_type not in {"REGULAR", "SUPPLEMENTARY"}:
            repairs.append(f"{student_id}/{row.get('course_code')}: exam_type {exam_type!r} -> REGULAR")
            exam_type = "REGULAR"
        fixed_results.append(
            {
                "course_code": str(row.get("course_code", "")).strip(),
                "exam_session": session,
                "exam_type": exam_type,
                "internal_marks": internal,
                "external_marks": external,
                "total_marks": total,
                "max_marks": MAX_TOTAL,
                "result": result,
            }
        )
    student = dict(student)
    student["results"] = fixed_results

    # Clamp attendance into a legal range.
    fixed_attendance = []
    for row in student.get("attendance", []) or []:
        if not isinstance(row, dict):
            continue
        try:
            held = int(str(row.get("classes_held", 0)).strip())
            attended = int(str(row.get("classes_attended", 0)).strip())
        except ValueError:
            repairs.append(f"{student_id}: dropped an attendance row with non-numeric values")
            continue
        if attended > held:
            repairs.append(f"{student_id}/{row.get('course_code')}: attended {attended} clamped to held {held}")
            attended = held
        if held <= 0:
            repairs.append(f"{student_id}/{row.get('course_code')}: attendance row dropped (held <= 0)")
            continue
        fixed_attendance.append(
            {
                "course_code": str(row.get("course_code", "")).strip(),
                "classes_held": held,
                "classes_attended": attended,
            }
        )
    student["attendance"] = fixed_attendance

    # Count backlogs the same way the tools do: the latest attempt per course
    # wins, so a cleared supplementary attempt removes the backlog.
    computed_backlogs = active_backlog_count(fixed_results)
    try:
        declared = int(str(student.get("active_backlogs", -1)).strip())
    except ValueError:
        declared = -1
    if declared != computed_backlogs:
        repairs.append(f"{student_id}: active_backlogs corrected {declared} -> {computed_backlogs}")
    student["active_backlogs"] = computed_backlogs
    return student, repairs


