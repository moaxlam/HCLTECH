def load_prompt_template() -> str:
    text = (PROJECT_ROOT / "prompts" / "generate_students.md").read_text(encoding="utf-8")
    marker = "## Batch request"
    head = text.split(marker, 1)[0]
    # Everything above the batch request block is sent verbatim.
    return head.rstrip() + "\n"


def build_batch_prompt(count: int, programme: str, batch_year: int, first: int, last: int) -> str:
    return (
        load_prompt_template()
        + "\n## Batch request\n\n"
        + f"Generate exactly {count} students of programme {programme}, batch {batch_year}, using "
        + f"student IDs from S{first} to S{last}. Reply with the JSON object described above.\n"
    )


def call_ollama(prompt: str, model: str, host: str, temperature: float, seed: int, timeout: int = 240) -> str:
    payload = json.dumps(
        {
            "model": model,
            "prompt": prompt,
            "stream": False,
            "format": "json",
            # Capped so a slow host still returns a usable batch inside the budget.
            "options": {"temperature": temperature, "seed": seed, "num_predict": 1200},
        }
    ).encode("utf-8")
    request = urllib.request.Request(
        f"{host.rstrip('/')}/api/generate",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        body = json.loads(response.read().decode("utf-8"))
    return body.get("response", "")


def extract_students(raw: str) -> list[dict[str, Any]]:
    """Pull the student list out of a model reply, tolerating stray prose."""
    raw = raw.strip()
    if raw.startswith("```"):
        raw = re.sub(r"^```[a-zA-Z]*\s*", "", raw)
        raw = re.sub(r"```\s*$", "", raw)
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", raw, re.DOTALL)
        if not match:
            return []
        try:
            parsed = json.loads(match.group(0))
        except json.JSONDecodeError:
            return []
    if isinstance(parsed, dict):
        students = parsed.get("students", [])
    elif isinstance(parsed, list):
        students = parsed
    else:
        students = []
    return [student for student in students if isinstance(student, dict)]


