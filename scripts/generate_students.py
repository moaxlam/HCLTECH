#!/usr/bin/env python
"""Generate the synthetic student dataset (Annex C schema).

Three producers write the same four CSV files:

``--source hybrid`` (default, fast)
    A small block of students is generated by a local Ollama model with the
    verbatim prompt in ``prompts/generate_students.md``, then the rest of the
    requested total is filled in deterministically, then the exact edge-case
    students are added. A wall-clock budget bounds the model time, so the command
    always finishes quickly and the log says how much came from the model.

``--source llm``
    Model only, no deterministic fill (slower; every batch waits for the model).

``--source deterministic``
    No model at all. Reproducible and instant; this is what produced the
    committed dataset.

Raw model replies are kept in ``data/generated_raw/`` so the mistakes the model
made can be inspected, and every repair is counted in ``data/generation_log.json``.

Usage
-----
    python scripts/generate_students.py                      # hybrid, ~2 minutes
    python scripts/generate_students.py --source deterministic
    python scripts/generate_students.py --source hybrid --count 8 --total 30 --budget-seconds 240
    python scripts/generate_students.py --source llm --model llama3.1:8b --count 24
"""

