def write_csvs(out_dir: Path, students: list[dict[str, Any]]) -> dict[str, int]:
    out_dir.mkdir(parents=True, exist_ok=True)
    attendance_rows = []
    result_rows = []
    student_rows = []
    for student in students:
        student_rows.append(
            {key: student[key] for key in ("student_id", "full_name", "programme", "batch_year", "current_semester", "cgpa", "active_backlogs")}
        )
        for row in student.get("attendance", []):
            attendance_rows.append({"student_id": student["student_id"], **row})
        for row in student.get("results", []):
            result_rows.append({"student_id": student["student_id"], **row})

    _write(out_dir / "students.csv", ["student_id", "full_name", "programme", "batch_year", "current_semester", "cgpa", "active_backlogs"], student_rows)
    _write(out_dir / "courses.csv", ["course_code", "course_name", "programme", "semester", "credits"], COURSES)
    _write(out_dir / "attendance.csv", ["student_id", "course_code", "classes_held", "classes_attended"], attendance_rows)
    _write(
        out_dir / "results.csv",
        ["student_id", "course_code", "exam_session", "exam_type", "internal_marks", "external_marks", "total_marks", "max_marks", "result"],
        result_rows,
    )
    return {
        "students": len(student_rows),
        "courses": len(COURSES),
        "attendance": len(attendance_rows),
        "results": len(result_rows),
    }


def _write(path: Path, columns: list[str], rows: list[dict[str, Any]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        for row in rows:
            writer.writerow({column: row.get(column, "") for column in columns})


def deterministic_block(
    total: int, first_id: int, rng: random.Random
) -> list[dict[str, Any]]:
    """Deterministic students spread evenly over both programmes and batches."""
    plan = [
        ("B.Tech CSE", 2023), ("B.Tech CSE", 2024),
        ("B.Tech ECE", 2023), ("B.Tech ECE", 2024),
    ]
    per_plan = total // len(plan)
    remainder = total % len(plan)
    students: list[dict[str, Any]] = []
    next_id = first_id
    for index, (programme, batch_year) in enumerate(plan):
        size = per_plan + (1 if index < remainder else 0)
        if size <= 0:
            continue
        students.extend(deterministic_batch(size, programme, batch_year, next_id, rng))
        next_id += size
    return students


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the synthetic student dataset")
    parser.add_argument(
        "--source",
        choices=["hybrid", "llm", "deterministic"],
        default="hybrid",
        help="hybrid (default): a small model block then a deterministic fill",
    )
    parser.add_argument("--count", type=int, default=8, help="students asked of the model")
    parser.add_argument("--total", type=int, default=30, help="total students in the dataset")
    parser.add_argument("--batch-size", type=int, default=2)
    parser.add_argument("--model", default="llama3.2:latest", help="use llama3.2:1b for speed")
    parser.add_argument("--host", default="http://localhost:11434")
    parser.add_argument("--temperature", type=float, default=0.4)
    parser.add_argument("--seed", type=int, default=20261010)
    parser.add_argument("--retries", type=int, default=1)
    parser.add_argument(
        "--budget-seconds",
        type=float,
        default=240.0,
        help="wall-clock limit for the model block; 0 means no limit",
    )
    parser.add_argument("--out", default=str(PROJECT_ROOT / "data"))
    parser.add_argument("--no-edge-cases", action="store_true")
    args = parser.parse_args()

    out_dir = Path(args.out)
    rng = random.Random(args.seed)
    log: dict[str, Any] = {"source": args.source, "requested_from_model": args.count, "total": args.total}

    started = time.monotonic()
    students: list[dict[str, Any]] = []
    if args.source in {"hybrid", "llm"}:
        want = args.count if args.source == "llm" else min(args.count, args.total)
        produced, llm_log = generate_from_llm(
            args, count=want, first_id=1001, budget_seconds=args.budget_seconds
        )
        log.update(llm_log)
        students.extend(produced)
        log["model_student_ids"] = [student["student_id"] for student in produced]
        if not produced:
            print("no students came back from the model; the deterministic producer will fill the dataset")

    if args.source == "deterministic":
        students = deterministic_block(args.total, 1001, rng)
        log["model_student_ids"] = []
    elif len(students) < args.total:
        fill_from = 1001 + len(students)
        filled = deterministic_block(args.total - len(students), fill_from, rng)
        students.extend(filled)
        log["deterministic_student_ids"] = [student["student_id"] for student in filled]

    if not args.no_edge_cases:
        students.extend(edge_case_students())
    log["seconds"] = round(time.monotonic() - started, 1)

    counts = write_csvs(out_dir, students)

    report = validate_dataset(
        [row for row in _read(out_dir / "students.csv")],
        _read(out_dir / "courses.csv"),
        _read(out_dir / "attendance.csv"),
        _read(out_dir / "results.csv"),
    )
    log["counts"] = counts
    log["validation_ok"] = report.ok
    log["violations"] = [str(violation) for violation in report.violations]
    log["edge_cases"] = report.coverage.get("edge_cases", {})
    (out_dir / "generation_log.json").write_text(json.dumps(log, indent=2), encoding="utf-8")

    print(report.summary())
    print(f"wrote {counts} to {out_dir}")
    return 0 if report.ok else 1


def _read(path: Path) -> list[dict[str, Any]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return [dict(row) for row in csv.DictReader(handle)]


if __name__ == "__main__":
    raise SystemExit(main())
